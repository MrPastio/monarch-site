export function findProductUpdate(version: string): ProductUpdate | null {
  return productUpdates.find((update) => update.version === version)
    ?? productUpdates.find((update) => update.version === productVersion(version))
    ?? null;
}

export function isPublicProductUpdate(
  update: ProductUpdate,
): update is PublicProductUpdate {
  return update.status !== "draft";
}
