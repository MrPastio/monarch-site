/**
 * Product history, ported from the previous site (marketing-site/app/content/updates.ts)
 * and completed with 0.2.4.1 and 0.2.3.8 from their GitHub release notes.
 */
function productVersion(version: string): string {
  const parts = version.split(".");
  return parts.length === 4 && parts[3] === "0" ? parts.slice(0, 3).join(".") : version;
}

type ProductUpdateContent = {
  version: string;
  title: string;
  summary: string;
  howItWorks: string;
  scale?: "major";
  categories: readonly UpdateCategory[];
  tags: readonly string[];
  audience: string;
  spotlight?: {
    statement: string;
    outcomes: readonly {
      label: string;
      title: string;
      description: string;
    }[];
    flow: readonly {
      label: string;
      title: string;
      description: string;
    }[];
    trust: readonly {
      title: string;
      description: string;
    }[];
  };
  changes: readonly {
    title: string;
    description: string;
  }[];
  verification?: {
    checkedOn: string;
    passed: readonly string[];
    pending: readonly string[];
  };
};

export type PublishedProductUpdate = ProductUpdateContent & {
  status: "published";
  publishedOn: string;
};

export type WithdrawnProductUpdate = ProductUpdateContent & {
  status: "withdrawn";
  publishedOn: string;
  withdrawal: {
    reason: string;
    supersededBy?: string;
  };
};

export type DraftProductUpdate = ProductUpdateContent & {
  status: "draft";
};

export type DevelopmentProductUpdate = ProductUpdateContent & {
  status: "development";
  updatedOn: string;
};

export type ProductUpdate =
  | PublishedProductUpdate
  | WithdrawnProductUpdate
  | DevelopmentProductUpdate
  | DraftProductUpdate;

export type PublicProductUpdate =
  | PublishedProductUpdate
  | WithdrawnProductUpdate
  | DevelopmentProductUpdate;

